/** Both tables, for the tests and a future language switch */
export const TABLES = { de, en }

let current = en
let currentLang = 'en'

/** de... means German, everything else English */
export function setLanguage(lang) {
  const isDe = typeof lang === 'string' && lang.toLowerCase().startsWith('de')
  current = isDe ? de : en
  currentLang = isDe ? 'de' : 'en'
}

let control = null
const filled = new Map()
// what {ws} reads when workplace.control names no workspace
const NO_CONTROL = { en: 'control', de: 'Steuerung' }

/** The control workspace (workplace.control): every {ws} in the texts becomes its name */
export function setControl(name) {
  control = typeof name === 'string' && name.trim() ? name.trim() : null
  filled.clear()
}

function fill(value, ws) {
  if (typeof value === 'string') return value.replaceAll('{ws}', ws)
  if (typeof value === 'function') return (...a) => fill(value(...a), ws)
  if (Array.isArray(value)) return value.map(v => fill(v, ws))
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, fill(v, ws)]))
  return value
}

export function T() {
  const ws = control ?? NO_CONTROL[currentLang]
  const key = `${currentLang}/${ws}`
  if (!filled.has(key)) filled.set(key, fill(current, ws))
  return filled.get(key)
}

/** The active language code, for Intl formatting and the html lang attribute */
export function language() {
  return currentLang
}

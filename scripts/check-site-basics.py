"""The Pages site stands on the same rules as the rest of the repo.

docs/ is hand authored and served by GitHub Pages with no build step, so the
things a generator would guarantee have to be checked instead. Five rules,
each of which had drifted when this was written:

1. Every page names its canonical URL (`<link rel="canonical">`, equal to its
   `og:url`), and every page is in docs/sitemap.xml, and nothing else is.
   Only the start page had a canonical link and there was no sitemap at all.
   Pages under the cockpit work (`cockpit*`) are in the sitemap but exempt
   from the canonical rule here: their markup is owned by that work.
   "Page" means a top-level docs/*.html. Subdirectories are not walked: the
   one published there, docs/cockpit-demo/, is a generated copy of the
   cockpit, owned and regenerated by the cockpit work, not a site page.
2. docs/robots.txt names the sitemap; docs/404.html exists, is `noindex`,
   carries a `<base>` equal to the path of SITE so its assets load at any
   depth, and links home.
3. A page with a German half (`data-lang="de"`) says so to link previews:
   `og:locale` en_US plus `og:locale:alternate` de_DE. The exception that
   allows the German half is rules/language-policy.md § 3.
4. The site palette and fonts in docs/assets/brand.css are the ones the
   `site:` block of DESIGN.md declares, value for value, light and dark,
   and no later top-level `:root` or `html.dark` block sets a site token
   again (an `@media` block may, print maps dark to light on purpose).
   AGENTS.md § Design System says no brand colour is hand-picked outside
   DESIGN.md; the site layer was the one place that did.
5. A schema `$id` that points at the Pages site resolves to a file under
   docs/, and no two schemas share an `$id`. Thirty-two `$id`s pointed at
   Pages addresses that answered 404; they are `urn:` identifiers now, and
   this keeps a new one from pointing at nothing.

Run: python3 scripts/check-site-basics.py
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path
from urllib.parse import urlparse

import yaml

REPO = Path(__file__).resolve().parents[1]
SITE = "https://bks-lab.github.io/open-bridge/"
NOT_FOUND = "404.html"
# Pages whose markup belongs to the cockpit work: listed in the sitemap, not
# held to the canonical rule by this checker.
CANONICAL_EXEMPT = ("cockpit",)
MARKER = "Source: DESIGN.md `site:`"

CANONICAL = re.compile(r'<link\s+rel="canonical"\s+href="([^"]+)"')
OG_URL = re.compile(r'<meta\s+property="og:url"\s+content="([^"]+)"')
OG_LOCALE = re.compile(r'<meta\s+property="og:locale"\s+content="([^"]+)"')
OG_ALT = re.compile(r'<meta\s+property="og:locale:alternate"\s+content="([^"]+)"')
LOC = re.compile(r"<loc>\s*([^<\s]+)\s*</loc>")
VAR_HEX = re.compile(r"--([A-Za-z0-9-]+)\s*:\s*(#[0-9A-Fa-f]{3,8})\b")
FONT_FACE = re.compile(r'@font-face\s*\{[^}]*font-family\s*:\s*"([^"]+)"')
FONT_DISPLAY = re.compile(r'--font-display\s*:\s*"([^"]+)"')
ROOT_ID = re.compile(r"""^\$id\s*:\s*["']?([^"'\s#]+)["']?\s*(?:#.*)?$""", re.M)
SKIP_DIRS = {"node_modules", "__pycache__", "venv", ".venv"}
# Paths under the root that hold frozen copies, not live files: a closed task keeps
# files as they were, so an old $id there is history rather than drift.
SKIP_PATHS = {Path("work/done")}


def site_path() -> str:
    """The path the site is served under, which the 404 page's <base> must name."""
    path = urlparse(SITE).path or "/"
    return path if path.endswith("/") else path + "/"


def url_for(name: str) -> str:
    return SITE if name == "index.html" else SITE + name


def pages(docs: Path) -> list[Path]:
    return sorted(p for p in docs.glob("*.html") if not p.name.startswith("_"))


def check_pages(root: Path) -> list[str]:
    docs = root / "docs"
    out: list[str] = []
    listed = [p for p in pages(docs) if p.name != NOT_FOUND]
    if not listed:
        return ["docs/: no pages found"]

    for p in listed:
        text = p.read_text(encoding="utf-8")
        want = url_for(p.name)
        if not p.name.startswith(CANONICAL_EXEMPT):
            canon = CANONICAL.search(text)
            if not canon:
                out.append(f"docs/{p.name}: no <link rel=\"canonical\">, want {want}")
            elif canon.group(1) != want:
                out.append(f"docs/{p.name}: canonical is {canon.group(1)}, want {want}")
            og = OG_URL.search(text)
            if og and og.group(1) != want:
                out.append(f"docs/{p.name}: og:url is {og.group(1)}, want {want}")
            if 'data-lang="de"' in text:
                loc, alt = OG_LOCALE.search(text), OG_ALT.search(text)
                if not loc or loc.group(1) != "en_US":
                    out.append(f"docs/{p.name}: bilingual page needs og:locale en_US")
                if not alt or alt.group(1) != "de_DE":
                    out.append(f"docs/{p.name}: bilingual page needs og:locale:alternate de_DE")

    sm = docs / "sitemap.xml"
    if not sm.is_file():
        out.append("docs/sitemap.xml is missing")
    else:
        locs = LOC.findall(sm.read_text(encoding="utf-8"))
        wanted = {url_for(p.name): p.name for p in listed}
        for url, name in wanted.items():
            if url not in locs:
                out.append(f"docs/{name}: not in docs/sitemap.xml ({url})")
        for url in locs:
            if url not in wanted:
                out.append(f"docs/sitemap.xml lists {url}, which is no page (or is the 404 page)")
        if len(locs) != len(set(locs)):
            out.append("docs/sitemap.xml lists a URL twice")

    robots = docs / "robots.txt"
    if not robots.is_file():
        out.append("docs/robots.txt is missing")
    elif f"Sitemap: {SITE}sitemap.xml" not in robots.read_text(encoding="utf-8"):
        out.append(f"docs/robots.txt does not name the sitemap (Sitemap: {SITE}sitemap.xml)")

    nf = docs / NOT_FOUND
    if not nf.is_file():
        out.append("docs/404.html is missing")
    else:
        text = nf.read_text(encoding="utf-8")
        if not re.search(r'<meta\s+name="robots"\s+content="[^"]*noindex', text):
            out.append("docs/404.html: needs <meta name=\"robots\" content=\"noindex\">")
        base = re.search(r'<base\s+href="([^"]*)"', text)
        if not base:
            out.append(f"docs/404.html: needs <base href=\"{site_path()}\"> so assets load at any depth")
        elif base.group(1) != site_path():
            out.append(f"docs/404.html: <base href> is {base.group(1)}, want {site_path()} (the path of SITE)")
        if not re.search(r'href="(index\.html|\./)"', text):
            out.append("docs/404.html: needs a link back to the start page")
    return out


def front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    data = yaml.safe_load(text[3:end]) if end > 0 else None
    return data if isinstance(data, dict) else {}


def css_block(css: str, selector: str, start: int) -> str:
    i = css.find(selector + "{", start)
    if i < 0:
        return ""
    j = css.find("}", i)
    return css[i:j]


def after_comment(css: str, at: int) -> int:
    """`at`, or the end of the comment `at` sits in, so a scan starts in code."""
    if css.rfind("/*", 0, at) > css.rfind("*/", 0, at):
        end = css.find("*/", at)
        return len(css) if end < 0 else end + 2
    return at


def top_level_blocks(css: str, selector: str, start: int) -> list[str]:
    """Bodies of every `selector{...}` at brace depth 0 from `start` on.

    Blocks inside an at-rule (`@media print{ html.dark{...} }`) sit at depth 1
    and are left out: they apply only under that condition.
    """
    found: list[str] = []
    depth, i, n = 0, start, len(css)
    while i < n:
        c = css[i]
        if c == "/" and css.startswith("/*", i):
            end = css.find("*/", i + 2)
            i = n if end < 0 else end + 2
            continue
        if depth == 0 and css.startswith(selector + "{", i) and (i == 0 or not (css[i - 1].isalnum() or css[i - 1] in "-_.#")):
            j = css.find("}", i)
            found.append(css[i:j if j >= 0 else n])
            i = n if j < 0 else j + 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth = max(0, depth - 1)
        i += 1
    return found


def check_design(root: Path) -> list[str]:
    design = root / "DESIGN.md"
    if not design.is_file():
        return ["DESIGN.md is missing"]
    site = front_matter(design).get("site")
    if not isinstance(site, dict):
        return ["DESIGN.md: no `site:` block in the front matter"]
    sheet = root / str(site.get("stylesheet") or "docs/assets/brand.css")
    if not sheet.is_file():
        return [f"DESIGN.md site.stylesheet {sheet.relative_to(root)} does not exist"]
    css = sheet.read_text(encoding="utf-8")
    rel = sheet.relative_to(root)
    at = css.find(MARKER)
    if at < 0:
        return [f"{rel}: no '{MARKER}' marker, so the site layer cannot be found"]

    out: list[str] = []
    for key, selector, label in (("colors", ":root", "light"), ("colorsDark", "html.dark", "dark")):
        declared = {str(k): str(v).upper() for k, v in (site.get(key) or {}).items()}
        found = {k: v.upper() for k, v in VAR_HEX.findall(css_block(css, selector, at))}
        for name in sorted(declared.keys() | found.keys()):
            d, f = declared.get(name), found.get(name)
            if d == f:
                continue
            if f is None:
                out.append(f"{rel} ({label}): --{name} missing, DESIGN.md site.{key} says {d}")
            elif d is None:
                out.append(f"{rel} ({label}): --{name}:{f} is not in DESIGN.md site.{key}")
            else:
                out.append(f"{rel} ({label}): --{name} is {f}, DESIGN.md site.{key} says {d}")
        for later in top_level_blocks(css, selector, after_comment(css, at))[1:]:
            for name, value in VAR_HEX.findall(later):
                if name in declared:
                    out.append(f"{rel} ({label}): --{name} is set twice after the marker (later {selector} sets {value.upper()}); keep one")

    fonts = site.get("fonts") or {}
    faces = set(FONT_FACE.findall(css[at:]))
    want = {str(v) for v in fonts.values()}
    if faces != want:
        out.append(f"{rel}: @font-face families {sorted(faces)} differ from DESIGN.md site.fonts {sorted(want)}")
    disp = FONT_DISPLAY.search(css[at:])
    if fonts.get("display") and (not disp or disp.group(1) != fonts["display"]):
        out.append(f"{rel}: --font-display does not lead with DESIGN.md site.fonts.display ({fonts['display']})")
    return out


def schema_files(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath).relative_to(root)
        dirnames[:] = [d for d in dirnames
                       if not d.startswith(".") and d not in SKIP_DIRS and here / d not in SKIP_PATHS]
        for f in filenames:
            if f.endswith((".yaml", ".yml")):
                yield Path(dirpath) / f


def check_schema_ids(root: Path) -> list[str]:
    out: list[str] = []
    seen: dict[str, Path] = {}
    for path in schema_files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "$id" not in text:
            continue
        rel = path.relative_to(root)
        for sid in ROOT_ID.findall(text):
            if sid in seen:
                out.append(f"{rel}: $id {sid} is already the $id of {seen[sid]}")
            else:
                seen[sid] = rel
            if sid.startswith(SITE):
                target = root / "docs" / sid[len(SITE):]
                if not target.is_file():
                    out.append(f"{rel}: $id {sid} points at the Pages site, and docs/{sid[len(SITE):]} does not exist (use urn:open-bridge:schema:<name>)")
    return out


def collect(root: Path) -> list[str]:
    return check_pages(root) + check_design(root) + check_schema_ids(root)


def main() -> int:
    problems = collect(REPO)
    if problems:
        print(f"check-site-basics: {len(problems)} problem(s):\n", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    n = len([p for p in pages(REPO / "docs") if p.name != NOT_FOUND])
    print(f"check-site-basics: {n} pages canonical and in the sitemap, site palette matches DESIGN.md, schema $ids resolve")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

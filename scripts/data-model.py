def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true",
                        help="regenerate the table, the ring and docs/families.md")
    parser.add_argument("--mutate", action="store_true", help="prove every check can fail")
    parser.add_argument("--root", default=str(REPO_ROOT), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = Path(args.root)

    if args.mutate:
        survivors = mutate(root)
        if survivors:
            print("data-model --mutate: these softenings went unnoticed:", file=sys.stderr)
            for s in survivors:
                print(f"  - {s}", file=sys.stderr)
            return 1
        print("data-model --mutate: every needle produced a finding")
        return 0

    if args.write:
        changed = write(root)
        print("data-model: rewrote " + (", ".join(changed) if changed else "nothing, all in sync"))
        return 0

    for w in warnings(root):
        print(f"data-model: warning: {w}", file=sys.stderr)
    problems = check(root)
    if problems:
        print("data-model: the model and the tree disagree:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1
    rows = load_model(root)["families"]
    local = sorted(_norm(r["path"]) for r in rows if r.get("origin") == INSTANCE_MODEL)
    note = (f" ({len(local)} described in {INSTANCE_MODEL} and left out of every rendering: "
            f"{', '.join(local)})") if local else ""
    kernel = "AGENTS.md holds to the kernel" if is_core_checkout(root) else "kernel guard advisory in a fork"
    print(f"data-model: {len(rows)} families, each described once{note}; "
          f"table, ring and {FAMILIES} match {CORE_MODEL}; {kernel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
